// gen-mock.mjs — 从 bridge-contract.json 自动生成 mock.js
//
// 设计：
//   - 契约 JSON 是唯一事实来源
//   - 每个桥命名空间生成一个 mock 对象
//   - invoke → function() { return Promise.resolve(undefined); }
//   - send   → function() { return undefined; }
//   - event  → function() { return NOOP; }  // 返回退订函数
//   - sync   → function() { return null; }
//   - __has(method) → boolean 能力探测
//   - __unsupported(method) → 结构化提示
//
// 产物：harmony/entry/src/main/resources/rawfile/injected/mock.js
// （由 build-injected.mjs 统一打包，或独立加载）
//
// 用法：
//   node scripts/gen-mock.mjs          → 写入 mock.js
//   node scripts/gen-mock.mjs --check   → 只比对不写盘
