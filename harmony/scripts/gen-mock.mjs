// ─── 生成 mock.js 内容 ───
function generateMockJs(contract) {
  const lines = [];
  lines.push('// AUTO-GENERATED by gen-mock.mjs — DO NOT EDIT MANUALLY');
  lines.push('// Source: bridge-contract.json (derived from preload source code)');
  lines.push('//');
  lines.push('// This file provides contract-driven mock implementations for all bridge');
  lines.push('// namespaces. The makeBridge Proxy in shell.ts uses these as the base layer;');
  lines.push('// ArkTS registerJavaScriptProxy merges real implementations on top.');
  lines.push('//');
  lines.push('// Capability detection: __has(method) → boolean');
  lines.push('// Unsupported diagnostic: __unsupported(method) → { method, bridge, message }');
  lines.push('');

  // 生成 NOOP 函数
  lines.push('var NOOP = function () {};');
  lines.push('');

  // 为每个 app 生成桥 mock
  for (const [app, bridges] of Object.entries(contract)) {
    if (bridges._error) {
      lines.push(`// ${app}: SKIPPED (${bridges._error})`);
      lines.push('');
      continue;
    }

    for (const [ns, methods] of Object.entries(bridges)) {
      if (typeof methods !== 'object' || methods._error) continue;

      lines.push(`// ─── ${app}.${ns} ───`);
      lines.push(`var ${ns}_mock = {`);

      // __has 方法：能力探测
      lines.push('  __has: function (method) {');
      lines.push('    return Object.prototype.hasOwnProperty.call(this, method) && typeof this[method] === "function";');
      lines.push('  },');

      // __unsupported 方法：结构化提示
      lines.push('  __unsupported: function (method) {');
      lines.push(`    return { method: method, bridge: "${ns}", message: "Method not yet implemented on HarmonyOS" };`);
      lines.push('  },');

      // 每个契约方法
      for (const [methodName, info] of Object.entries(methods)) {
        const bootKey = `${ns}.${methodName}`;
        const bootValueFn = BOOT_METHODS[bootKey];
        const bootValue = bootValueFn ? bootValueFn() : null;

        if (info.kind === 'invoke') {
          if (bootValue !== null) {
            lines.push(`  ${methodName}: function () { return Promise.resolve(${bootValue}); },`);
          } else {
            lines.push(`  ${methodName}: function () { return Promise.resolve(undefined); },`);
          }
        } else if (info.kind === 'send') {
          lines.push(`  ${methodName}: function () { return undefined; },`);
        } else if (info.kind === 'event') {
          lines.push(`  ${methodName}: function () { return NOOP; },`);
        } else if (info.kind === 'sync') {
          if (bootValue !== null) {
            lines.push(`  ${methodName}: function () { return ${bootValue}; },`);
          } else {
            lines.push(`  ${methodName}: function () { return null; },`);
          }
        } else {
          // unknown — treat as invoke (safest default)
          lines.push(`  ${methodName}: function () { return Promise.resolve(undefined); },`);
        }
      }

      lines.push('};');
      lines.push('');
    }
  }

  // 导出映射：桥名 → mock 对象
  lines.push('// ─── 桥名 → mock 对象映射 ───');
  lines.push('var BRIDGE_MOCKS = {');
  for (const [app, bridges] of Object.entries(contract)) {
    if (bridges._error) continue;
    for (const ns of Object.keys(bridges)) {
      if (typeof bridges[ns] !== 'object' || bridges[ns]._error) continue;
      lines.push(`  "${ns}": ${ns}_mock,`);
    }
  }
  lines.push('};');
  lines.push('');

  // 导出
  lines.push('// Export for shell.ts consumption');
  lines.push('if (typeof module !== "undefined" && module.exports) {');
  lines.push('  module.exports = { BRIDGE_MOCKS, NOOP };');
  lines.push('}');

  return lines.join('\n');
}

// 导出供反例自测使用
export { generateMockJs };

// ─── 主入口 ───
export function generateMock() {
  if (!existsSync(CONTRACT_PATH)) {
    throw new Error('bridge-contract.json 不存在，需要先运行 gen-bridge-contract');
  }
  const contract = JSON.parse(readFileSync(CONTRACT_PATH, 'utf8'));
  return generateMockJs(contract);
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const mockJs = generateMock();

  if (process.argv.includes('--check')) {
    if (!existsSync(OUTPUT_PATH)) {
      console.error('FAIL: mock.js 不存在，需要先运行 gen-mock');
      process.exit(1);
    }
    const existing = readFileSync(OUTPUT_PATH, 'utf8');
    if (existing !== mockJs) {
      console.error('FAIL: mock.js 与 bridge-contract.json 不一致');
      console.error('  运行 `node scripts/gen-mock.mjs` 重新生成');
      process.exit(1);
    }
    console.error('OK: mock.js 与 bridge-contract.json 一致');
    process.exit(0);
  }

  // 确保输出目录存在
  const outputDir = dirname(OUTPUT_PATH);
  if (!existsSync(outputDir)) {
    // rawfile/injected 目录可能不存在（构建产物）
    // 退而求其次写到 scripts 目录
    const altOutput = resolve(__dirname, 'mock.generated.js');
    writeFileSync(altOutput, mockJs);
    console.error(`mock.js → ${altOutput} (rawfile/injected 不存在，写到 scripts 目录)`);
  } else {
    writeFileSync(OUTPUT_PATH, mockJs);
    console.error(`mock.js → ${OUTPUT_PATH}`);
  }

  // 统计
  const contract = JSON.parse(readFileSync(CONTRACT_PATH, 'utf8'));
  let totalMethods = 0;
  for (const [app, bridges] of Object.entries(contract)) {
    if (bridges._error) continue;
    for (const [ns, methods] of Object.entries(bridges)) {
      if (typeof methods !== 'object' || methods._error) continue;
      totalMethods += Object.keys(methods).length;
    }
  }
  console.error(`TOTAL: ${totalMethods} methods across all bridges`);
}